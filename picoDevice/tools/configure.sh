#! /usr/bin/env bash
set -e

# Load environment variables from .env if it exists
if [ -f .env ]; then
    echo "Loading configuration from .env..."
    export $(cat .env | grep -v '^#' | xargs)
else
    echo "Warning: .env file not found. Using default values."
    echo "Please copy .env.example to .env and configure it."
    # Set defaults
    export WIFI_SSID="${WIFI_SSID:-default_ssid}"
    export WIFI_PASSWORD="${WIFI_PASSWORD:-default_password}"
    export API_URL="${API_URL:-http://192.168.1.100:8080}"
    export REFRESH_INTERVAL="${REFRESH_INTERVAL:-60}"
fi

# Legacy .env files configured API_HOST/API_PORT instead of API_URL.
if [ -z "$API_URL" ] && [ -n "$API_HOST" ]; then
    export API_URL="http://$API_HOST:${API_PORT:-80}"
    echo "Warning: API_HOST/API_PORT are deprecated; using API_URL=$API_URL. Replace them with API_URL in .env."
fi
if [ -z "$API_URL" ]; then
    echo "Error: API_URL is not set in .env (e.g. API_URL=http://192.168.1.100:8080)" >&2
    exit 1
fi

# Generate config file from environment variables
echo "Generating configuration..."
mkdir -p internal/config
cat > internal/config/generated.go <<EOF
// Code generated by build.sh - DO NOT EDIT
// This file is auto-generated from .env during build

package config

// Configuration constants loaded from .env at build time
const (
	WifiSSID        = "$WIFI_SSID"
	WifiPassword    = "$WIFI_PASSWORD"
	APIURL          = "$API_URL"
	RefreshInterval = $REFRESH_INTERVAL

	// Hardware test knobs, read by debug builds only; 0 disables them.
	// See .env.example.
	WifiTestFailJoins        = ${WIFI_TEST_FAIL_JOINS:-0}
	WifiTestOutageAfterCycle = ${WIFI_TEST_OUTAGE_AFTER_CYCLE:-0}
	WifiTestOutageFailJoins  = ${WIFI_TEST_OUTAGE_FAIL_JOINS:-0}
)
EOF

echo "✓ Configuration generated"
